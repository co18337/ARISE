/// The exercise library — reference data, and the plan as DATA.
///
/// Built for what is ACTUALLY available: a gym, a park with a pull-up bar, and
/// the road. The 2027 roadmap document was written on a "No Gym" premise and
/// lists ₹1,498 of resistance tubes and loop bands; that premise stopped being
/// true in September 2026 and none of that equipment was ever bought. There is
/// no band work here for that reason.
///
/// Two decisions worth knowing, both of them the user's:
///
/// WALKING IS NOT A SESSION. Brisk walks are gone as a day's work and sprint
/// work takes their place, to make fat loss come sooner. Walking survives only
/// as the recovery inside an interval and the way home afterwards.
///
/// SPRINTING IS APPROACHED, NOT ASSUMED. RESET uses `hill_strides` — short,
/// controlled, well short of maximum, with full recovery — before
/// `sprint_interval` arrives in FAT BURN. That is not a watering-down: a
/// hamstring torn in week two costs more weeks than the strides do, and
/// somebody starting from three push-ups has no sprint base to draw on yet.
///
/// The app schedules and records. Interpreting the body-composition scan or
/// the blood work stays with the doctor; what is used here is the SEGMENT
/// data, and only to decide which regions get more volume.
